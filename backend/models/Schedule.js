const mongoose = require('mongoose');

const scheduleSchema = new mongoose.Schema({
    userId: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'User',
        required: true
    },
    eventId: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'Event',
        required: true
    },
    startTime: {
        type: Date,
        required: true
    },
    endTime: {
        type: Date,
        required: true
    }
}, { timestamps: true });

// Prevent duplicate schedule entries for the same event and user
scheduleSchema.index({ userId: 1, eventId: 1 }, { unique: true });

module.exports = mongoose.model('Schedule', scheduleSchema);
